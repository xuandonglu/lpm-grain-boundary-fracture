static int *own, *shl, *pairid, *sidx, *optr, *olist, *fmap;
static int64_t *sptr;
static int npid, nf, nthr = 2;
/* state */
static double *u, *ev3, *rr, *xb, *d1p, *d2p, *pp, *d1s, *d2s, *Fb, *cb, *Dps, *fint, *gE, *gcor, *ubase;

static void *xread(FILE *f, size_t sz, size_t n)
{
    void *p = malloc(sz * (n ? n : 1));
    if (n && fread(p, sz, n, f) != n) { fprintf(stderr, "short read\n"); exit(2); }
    return p;
}

static void load(const char *path)
{
    FILE *f = fopen(path, "rb");
    if (!f) { fprintf(stderr, "cannot open %s\n", path); exit(2); }
    int64_t h[8]; double d[16] = {0};
    if (fread(h, 8, 8, f) != 8) { fprintf(stderr, "bad header\n"); exit(2); }
    ver = (int)h[3];
    if (fread(d, 8, ver == 2 ? 16 : 8, f) != (size_t)(ver == 2 ? 16 : 8)) { fprintf(stderr, "bad header\n"); exit(2); }
    N = h[0], nb = h[1], nsup = h[2];
    T = d[0], s_c = d[1], tie = d[2], kg = d[3], Lz = d[4];
    if (ver == 2) ul[0] = d[5], ul[1] = d[6], y0c = d[7], Hd = d[8], Wd = d[9], a0c = d[10];
    X = xread(f, 8, 3 * N); fixd = xread(f, 1, 3 * N); ubc = xread(f, 8, 3 * N);
    own = xread(f, 4, nb); shl = xread(f, 4, nb); pairid = xread(f, 4, nb); flag = xread(f, 1, nb);
    bn = xread(f, 8, 3 * nb); bd0 = xread(f, 8, nb); bkn = xread(f, 8, nb); bxi = xread(f, 8, nb);
    sptr = xread(f, 8, nb + 1); sidx = xread(f, 4, nsup); sw = xread(f, 8, nsup);
    if (ver == 2) { coh = xread(f, 1, nb); gmul = xread(f, 8, nb); }
    else { coh = calloc(nb, 1); gmul = malloc(nb * 8); for (int64_t b = 0; b < nb; b++) gmul[b] = 1.0; }  /* v1: harmonic */
    fclose(f);
    npid = 0;
    for (int64_t b = 0; b < nb; b++) if (pairid[b] + 1 > npid) npid = pairid[b] + 1;
    unsigned char *pal = malloc(npid);
    memset(pal, 1, npid);
    for (int64_t b = 0; b < nb; b++) if (flag[b] & 4) pal[pairid[b]] = 0;
    alive = malloc(nb);
    for (int64_t b = 0; b < nb; b++) alive[b] = pal[pairid[b]];
    free(pal);
    optr = calloc(N + 1, sizeof(int)); olist = malloc(nb * sizeof(int));
    for (int64_t b = 0; b < nb; b++) optr[own[b] + 1]++;
    for (int64_t i = 0; i < N; i++) optr[i + 1] += optr[i];
    int *fill = calloc(N, sizeof(int));
    for (int64_t b = 0; b < nb; b++) olist[optr[own[b]] + fill[own[b]]++] = (int)b;
    free(fill);
    fmap = malloc(3 * N * sizeof(int));
    nf = 0;
    for (int64_t k = 0; k < 3 * N; k++) fmap[k] = fixd[k] ? -1 : nf++;
    u = calloc(3 * N, 8); ev3 = calloc(3 * nb, 8); rr = calloc(nb, 8); xb = calloc(nb, 8);
    d1p = calloc(nb, 8); d2p = calloc(nb, 8); pp = calloc(nb, 8); d1s = calloc(nb, 8); d2s = calloc(nb, 8);
    Fb = calloc(nb, 8); cb = calloc(nb, 8); Dps = calloc(2 * N, 8); fint = calloc(3 * N, 8);
    gE = calloc(3 * N, 8); gcor = calloc(3 * N, 8); ubase = calloc(3 * N, 8);
}

/* ------------------------------------------------------------------ law and state */
static inline double lb(int64_t b) { return ul[shl[b]] * sqrt(gmul[b]); }

static inline void law(int64_t b, double x, double *phi, double *dphi, double *d2phi, double *psi, double *dpsi, double *d2psi)
{
    double kk = 2.0 * bkn[b];                       /* E / l^2 = 2 Kn (elastic consistency, independent of g) */
    if (coh[b] && x > 0.0) {
        double l = lb(b), t = x / l, e = exp(-t);
        *phi = kk * l * l * (1.0 - (1.0 + t) * e); *dphi = kk * x * e; *d2phi = kk * (1.0 - t) * e;
        *psi = x * e; *dpsi = (1.0 - t) * e; *d2psi = (t - 2.0) * e / l;
    } else {
        *phi = 0.5 * kk * x * x; *dphi = kk * x; *d2phi = kk; *psi = x; *dpsi = 1.0; *d2psi = 0.0;
    }
}

static double energy_acc;
/* bond kinematics, law, multibody sums, bond forces, internal forces; returns the stored energy expression
   sum_b phi_b / 2 + T/2 sum D^2 (the plmode 8 energy for symmetric models; only a diagnostic for ghost bonds) */
static void eval_state(void)
{
    double en = 0;
    #pragma omp parallel for num_threads(nthr) reduction(+:en)
    for (int64_t b = 0; b < nb; b++) {
        if (!alive[b]) continue;
        const double *n = bn + 3 * b; int i = own[b];
        double v[3] = {bd0[b] * n[0] + u[3 * i], bd0[b] * n[1] + u[3 * i + 1], bd0[b] * n[2] + u[3 * i + 2]};
        for (int64_t q = sptr[b]; q < sptr[b + 1]; q++) {
            int m = sidx[q];
            for (int c = 0; c < 3; c++) v[c] -= sw[q] * u[3 * m + c];
        }
        double r = sqrt(v[0] * v[0] + v[1] * v[1] + v[2] * v[2]);
        rr[b] = r; xb[b] = r - bd0[b];
        for (int c = 0; c < 3; c++) ev3[3 * b + c] = v[c] / r;
        double phi;
        law(b, xb[b], &phi, &d1p[b], &d2p[b], &pp[b], &d1s[b], &d2s[b]);
        en += 0.5 * phi;
    }
    #pragma omp parallel for num_threads(nthr) reduction(+:en)
    for (int64_t i = 0; i < N; i++) {
        double D0 = 0, D1 = 0;
        for (int k = optr[i]; k < optr[i + 1]; k++) {
            int b = olist[k];
            if (!alive[b]) continue;
            if (shl[b] == 0) D0 += pp[b]; else D1 += pp[b];
        }
        Dps[2 * i] = D0, Dps[2 * i + 1] = D1;
        en += 0.5 * T * (D0 * D0 + D1 * D1);
    }
    #pragma omp parallel for num_threads(nthr)
    for (int64_t b = 0; b < nb; b++) {
        if (!alive[b]) continue;
        int s = shl[b];
        double Db = 0;
        for (int64_t q = sptr[b]; q < sptr[b + 1]; q++) Db += sw[q] * Dps[2 * sidx[q] + s];
        double M = T * (Dps[2 * own[b] + s] + Db);
        Fb[b] = d1p[b] + d1s[b] * M;
        cb[b] = d2p[b] + d2s[b] * M;
    }
    #pragma omp parallel for num_threads(nthr)
    for (int64_t i = 0; i < N; i++) {
        double f[3] = {0, 0, 0};
        for (int k = optr[i]; k < optr[i + 1]; k++) {
            int b = olist[k];
            if (!alive[b]) continue;
            for (int c = 0; c < 3; c++) f[c] += Fb[b] * ev3[3 * b + c];
        }
        for (int c = 0; c < 3; c++) fint[3 * i + c] = f[c];
    }
    energy_acc = en;
    /* gradient of the surrogate energy (= P_in for ordinary bonds; differs at ghost bonds: their reactions on the supports) */
    memset(gE, 0, 3 * N * sizeof(double));
    for (int64_t b = 0; b < nb; b++) {
        if (!alive[b]) continue;
        const double *e = ev3 + 3 * b;
        double G = 0.5 * d1p[b] + T * d1s[b] * Dps[2 * own[b] + shl[b]];
        int i = own[b];
        for (int c = 0; c < 3; c++) gE[3 * i + c] += G * e[c];
        for (int64_t q = sptr[b]; q < sptr[b + 1]; q++)
            for (int c = 0; c < 3; c++) gE[3 * sidx[q] + c] -= sw[q] * G * e[c];
    }
    if (emode) memcpy(fint, gE, 3 * N * sizeof(double));
}

/* line-search merit: surrogate energy with the dead-load ghost-force correction at the base point u0 of the line search,
   E*(u) = Pi(u) - (dPi/du(u0) - P_in(u0)) . (u - u0), so that grad E* at u0 equals P_in(u0) (consistent Armijo slope); for models
   without ghost bonds the correction is zero (round-off) and E* = Pi, the fork's merit */
static void merit_base(void)
{
    for (int64_t k = 0; k < 3 * N; k++) { gcor[k] = fixd[k] ? 0.0 : gE[k] - fint[k]; ubase[k] = u[k]; }
}
static double merit(void)
{
    double s = 0;
    for (int64_t k = 0; k < 3 * N; k++) s += gcor[k] * (u[k] - ubase[k]);
    return energy_acc - s;
}

static double gmax_free(void)
{
    double m = 0;
    for (int64_t k = 0; k < 3 * N; k++) if (!fixd[k] && fabs(fint[k]) > m) m = fabs(fint[k]);
    return m;
}

/* ------------------------------------------------------------------ Jacobian rows (sparse accumulator per thread) */
typedef struct { double *acc; int *mark, *list, nl, stamp; } spa_t;

static inline void spa_add(spa_t *S, int col, const double c[3], double v)
{
    if (S->mark[col] != S->stamp) { S->mark[col] = S->stamp; S->list[S->nl++] = col; S->acc[3 * col] = S->acc[3 * col + 1] = S->acc[3 * col + 2] = 0.0; }
    S->acc[3 * col] += c[0] * v, S->acc[3 * col + 1] += c[1] * v, S->acc[3 * col + 2] += c[2] * v;
}

/* rows a += coef[a] * scale * d x_b  (d x_b = e_b . (du_i - sum w du_m)) */
static inline void add_V(spa_t *S, int b, const double coef[3], double scale)
{
    const double *e = ev3 + 3 * b;
    int i = own[b];
    for (int c = 0; c < 3; c++) spa_add(S, 3 * i + c, coef, scale * e[c]);
    for (int64_t k = sptr[b]; k < sptr[b + 1]; k++) {
        int m = sidx[k]; double w = sw[k];
        for (int c = 0; c < 3; c++) spa_add(S, 3 * m + c, coef, -scale * w * e[c]);
    }
}

/* rows += coef * d D_{p,s} */
static inline void add_D(spa_t *S, int p, int s, const double coef[3])
{
    for (int k = optr[p]; k < optr[p + 1]; k++) {
        int b = olist[k];
        if (shl[b] == s && alive[b]) add_V(S, b, coef, d1s[b]);
    }
}

static int clip_on = 0;
static double clipf = 1e-3;
static void row_block(spa_t *S, int i)
{
    S->stamp++; S->nl = 0;
    double cD[2][3] = {{0}};
    for (int k = optr[i]; k < optr[i + 1]; k++) {
        int b = olist[k];
        if (!alive[b]) continue;
        const double *e = ev3 + 3 * b;
        int s = shl[b];
        double cc = cb[b];
        if (clip_on && cc < clipf * 2.0 * bkn[b]) cc = clipf * 2.0 * bkn[b];   /* PD-clipped axial curvature (fork ub_tangent 2) */
        double c1[3] = {cc * e[0], cc * e[1], cc * e[2]};
        add_V(S, b, c1, 1.0);
        double g = Fb[b] / rr[b];                         /* geometric stiffness F/r (I - e e^T) d v_b */
        for (int c = 0; c < 3; c++) {
            double gc[3] = {g * ((c == 0) - e[0] * e[c]), g * ((c == 1) - e[1] * e[c]), g * ((c == 2) - e[2] * e[c])};
            spa_add(S, 3 * i + c, gc, 1.0);
            for (int64_t q = sptr[b]; q < sptr[b + 1]; q++) spa_add(S, 3 * sidx[q] + c, gc, -sw[q]);
        }
        for (int a = 0; a < 3; a++) cD[s][a] += T * d1s[b] * e[a];
        for (int64_t q = sptr[b]; q < sptr[b + 1]; q++) {
            double w = sw[q], c2[3] = {T * d1s[b] * w * e[0], T * d1s[b] * w * e[1], T * d1s[b] * w * e[2]};
            add_D(S, sidx[q], s, c2);
        }
    }
    for (int s = 0; s < 2; s++) add_D(S, i, s, cD[s]);
    double I3[3][3] = {{1, 0, 0}, {0, 1, 0}, {0, 0, 1}};
    for (int a = 0; a < 3; a++) spa_add(S, 3 * i + a, I3[a], kg);   /* tangent regularisation only (not in P_in) */
}

/* ------------------------------------------------------------------ CSR (free x free) on the intact pattern */
static MKL_INT *ia, *ja;
static double *va, *rhs, *dabs_;
static int *pcp, *pcol, *dpos;
static int64_t nnz;
static spa_t *spas;

static int cmpint(const void *a, const void *b) { int x = *(const int *)a, y = *(const int *)b; return (x > y) - (x < y); }

static void build_pattern(void)
{
    spa_t *S = &spas[0];
    pcp = malloc((N + 1) * sizeof(int));
    int64_t cap = 64 * N, tot = 0;
    pcol = malloc(cap * sizeof(int));
    pcp[0] = 0;
    for (int64_t i = 0; i < N; i++) {
        row_block(S, (int)i);
        qsort(S->list, S->nl, sizeof(int), cmpint);
        for (int k = 0; k < S->nl; k++) {
            int col = S->list[k];
            if (fmap[col] < 0) continue;
            if (tot >= cap) { cap *= 2; pcol = realloc(pcol, cap * sizeof(int)); }
            pcol[tot++] = col;
        }
        pcp[i + 1] = (int)tot;
    }
    ia = malloc((nf + 1) * sizeof(MKL_INT));
    nnz = 0;
    int r = 0;
    ia[0] = 0;
    for (int64_t i = 0; i < N; i++)
        for (int a = 0; a < 3; a++) {
            if (fmap[3 * i + a] < 0) continue;
            nnz += pcp[i + 1] - pcp[i];
            ia[++r] = (MKL_INT)nnz;
        }
    ja = malloc(nnz * sizeof(MKL_INT)); va = malloc(nnz * sizeof(double));
    rhs = malloc(nf * sizeof(double)); dabs_ = malloc(nf * sizeof(double)); dpos = malloc(nf * sizeof(int));
    r = 0;
    for (int64_t i = 0; i < N; i++)
        for (int a = 0; a < 3; a++) {
            if (fmap[3 * i + a] < 0) continue;
            MKL_INT o = ia[r];
            dpos[r] = -1;
            for (int k = pcp[i]; k < pcp[i + 1]; k++, o++) {
                ja[o] = fmap[pcol[k]];
                if (pcol[k] == 3 * i + a) dpos[r] = (int)o;
            }
            r++;
        }
}

static long assemble(void)
{
    long dropped = 0;
    #pragma omp parallel for schedule(dynamic, 64) num_threads(nthr) reduction(+:dropped)
    for (int64_t i = 0; i < N; i++) {
        spa_t *S = &spas[omp_get_thread_num()];
        if (fmap[3 * i] < 0 && fmap[3 * i + 1] < 0 && fmap[3 * i + 2] < 0) continue;
        row_block(S, (int)i);
        int inpat = 0;
        for (int k = 0; k < S->nl; k++) inpat += fmap[S->list[k]] >= 0;
        if (inpat > pcp[i + 1] - pcp[i]) dropped += inpat - (pcp[i + 1] - pcp[i]);
        for (int a = 0; a < 3; a++) {
            int fr = fmap[3 * i + a];
            if (fr < 0) continue;
            MKL_INT o = ia[fr];
            for (int k = pcp[i]; k < pcp[i + 1]; k++, o++) {
                int col = pcol[k];
                va[o] = (S->mark[col] == S->stamp) ? S->acc[3 * col + a] : 0.0;
            }
        }
    }
    for (int r = 0; r < nf; r++) dabs_[r] = fabs(va[dpos[r]]);
    return dropped;
}

/* ------------------------------------------------------------------ PARDISO */
static void *pt[64];
static MKL_INT iparm[64], mtype = 11, maxfct = 1, mnum = 1, msglvl = 0, nrhs = 1, perm_dummy;
static int analysed = 0, have_factor = 0, cgsL = 0;
static long n_cgs_ok = 0;
static long n_fact = 0, n_newton = 0, n_reject = 0, n_backoff = 0;
static double t_fact = 0, t_asm = 0;

static int psolve(double *x)
{
    MKL_INT err = 0, n = nf, phase;
    double t0 = omp_get_wtime();
    if (!analysed) {
        memset(pt, 0, sizeof pt); memset(iparm, 0, sizeof iparm);
        iparm[0] = 1; iparm[1] = 3; iparm[7] = 2; iparm[9] = 13; iparm[10] = 1; iparm[12] = 1; iparm[34] = 1;
        phase = 11;
        PARDISO(pt, &maxfct, &mnum, &mtype, &phase, &n, va, ia, ja, &perm_dummy, &nrhs, iparm, &msglvl, rhs, x, &err);
        if (err) return (int)err;
        analysed = 1;
    }
    /* GH_CGS = L > 0: CGS preconditioned with the previous LU factor (PARDISO iparm[3] = 10 L + 1, tolerance 10^-L);
       PARDISO refactorises only when CGS fails (iparm[19] < 0).  Inexact Newton directions; convergence is still
       measured on max |P_in|. */
    iparm[3] = (cgsL > 0 && have_factor) ? 10 * cgsL + 1 : 0;
    phase = 23;
    PARDISO(pt, &maxfct, &mnum, &mtype, &phase, &n, va, ia, ja, &perm_dummy, &nrhs, iparm, &msglvl, rhs, x, &err);
    if (iparm[3] > 0) { if (iparm[19] > 0) n_cgs_ok++; else n_fact++; } else n_fact++;
    have_factor = 1;
    t_fact += omp_get_wtime() - t0;
    return (int)err;
}

static int psolve_reuse(double *x)                /* back substitution with the current factor (phase 33) */
{
    MKL_INT err = 0, n = nf, phase = 33;
    double t0 = omp_get_wtime();
    iparm[3] = 0;
    PARDISO(pt, &maxfct, &mnum, &mtype, &phase, &n, va, ia, ja, &perm_dummy, &nrhs, iparm, &msglvl, rhs, x, &err);
    t_fact += omp_get_wtime() - t0;
    return (int)err;
}

/* ------------------------------------------------------------------ matrix-free Hessian of the surrogate energy Pi
   Pi = sum_b phi(x_b)/2 + T/2 sum_(p,s) D_ps^2,  x_b = |d0 n + u_i - sum_m w_m u_m| - d0,  g_b = dx_b/du (e_b at i,
   -w_m e_b at the supports).  H v = sum_b [c_b (g_b.v) + T psi'_b S_(i,s)] g_b + G_b/r_b L_b^T (I - e e^T) L_b v with
   c_b = phi''/2 + T psi'' D_(i,s), G_b = phi'/2 + T psi' D_(i,s), S_(p,s) = sum_(b in p,s) psi'_b (g_b.v).  PD clip of c_b
   (>= clip Kn_b) as the fork's prepare_hess. */
static double *hv_full, *hv_lv, *hv_sv, *hv_S, *hv_tb;
static int hclip_on = 0;
static double hclipf = 1e-3;

static void hv_alloc(void)
{
    hv_full = malloc(3 * N * sizeof(double)); hv_lv = malloc(3 * nb * sizeof(double)); hv_sv = malloc(nb * sizeof(double));
    hv_S = malloc(2 * N * sizeof(double)); hv_tb = malloc((size_t)nthr * 3 * N * sizeof(double));
}

static void hessvec_E(const double *vf, double *outf)
{
    for (int64_t k = 0; k < 3 * N; k++) hv_full[k] = fmap[k] >= 0 ? vf[fmap[k]] : 0.0;
    #pragma omp parallel for num_threads(nthr)
    for (int64_t b = 0; b < nb; b++) {
        if (!alive[b]) { hv_sv[b] = 0; continue; }
        int i = own[b];
        double L[3] = {hv_full[3 * i], hv_full[3 * i + 1], hv_full[3 * i + 2]};
        for (int64_t q = sptr[b]; q < sptr[b + 1]; q++) {
            int m = sidx[q];
            for (int c = 0; c < 3; c++) L[c] -= sw[q] * hv_full[3 * m + c];
        }
        const double *e = ev3 + 3 * b;
        for (int c = 0; c < 3; c++) hv_lv[3 * b + c] = L[c];
        hv_sv[b] = e[0] * L[0] + e[1] * L[1] + e[2] * L[2];
    }
    #pragma omp parallel for num_threads(nthr)
    for (int64_t p = 0; p < N; p++) {
        double S0 = 0, S1 = 0;
        for (int k = optr[p]; k < optr[p + 1]; k++) {
            int b = olist[k];
            if (!alive[b]) continue;
            if (shl[b] == 0) S0 += d1s[b] * hv_sv[b]; else S1 += d1s[b] * hv_sv[b];
        }
        hv_S[2 * p] = S0, hv_S[2 * p + 1] = S1;
    }
    #pragma omp parallel num_threads(nthr)
    {
        int t = omp_get_thread_num();
        double *tb = hv_tb + (size_t)t * 3 * N;
        memset(tb, 0, 3 * N * sizeof(double));
        #pragma omp for schedule(static)
        for (int64_t b = 0; b < nb; b++) {
            if (!alive[b]) continue;
            int i = own[b], sh = shl[b];
            const double *e = ev3 + 3 * b, *L = hv_lv + 3 * b;
            double Dq = Dps[2 * i + sh];
            double c = 0.5 * d2p[b] + T * d2s[b] * Dq;
            if (hclip_on && c < hclipf * bkn[b]) c = hclipf * bkn[b];
            double G = 0.5 * d1p[b] + T * d1s[b] * Dq, gr = G / rr[b];
            double ax = c * hv_sv[b] + T * d1s[b] * hv_S[2 * i + sh];
            double qv[3];
            for (int k = 0; k < 3; k++) qv[k] = ax * e[k] + gr * (L[k] - e[k] * hv_sv[b]);
            for (int k = 0; k < 3; k++) tb[3 * i + k] += qv[k];
            for (int64_t q = sptr[b]; q < sptr[b + 1]; q++) {
                int m = sidx[q];
                for (int k = 0; k < 3; k++) tb[3 * m + k] -= sw[q] * qv[k];
            }
        }
        #pragma omp barrier
        #pragma omp for schedule(static)
        for (int64_t k = 0; k < 3 * N; k++) {
            double sacc = 0;
            for (int tt = 0; tt < nthr; tt++) sacc += hv_tb[(size_t)tt * 3 * N + k];
            hv_full[k] = sacc;
        }
    }
    for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0) outf[fmap[k]] = hv_full[k] + kg * vf[fmap[k]];
}

/* ------------------------------------------------------------------ truncated Newton (GH_TN, fork drv_px minimize) */
static int tn_mode = 0;
static double *bjinv, *tn_tbuf;              /* 3x3 block-Jacobi inverses per particle; per-thread transpose buffers */
static long n_cg = 0, n_switch = 0, n_exact_in_tn = 0, n_flow = 0, n_etn = 0, n_force_finish = 0;
static double flowcap = 0.5, flowmu0 = 1.0;
static int flowreuse = 8;
static int pprule = 1;

/* out = 0.5 (J + J^T) v on the free dofs (J = va/ia/ja of the last assemble) */
static void symv(const double *v, double *out)
{
    #pragma omp parallel num_threads(nthr)
    {
        int t = omp_get_thread_num();
        double *tb = tn_tbuf + (size_t)t * nf;
        memset(tb, 0, nf * sizeof(double));
        #pragma omp for schedule(static)
        for (int r = 0; r < nf; r++) {
            double s = 0, vr = v[r];
            for (MKL_INT q = ia[r]; q < ia[r + 1]; q++) { s += va[q] * v[ja[q]]; tb[ja[q]] += va[q] * vr; }
            out[r] = 0.5 * s;
        }
        #pragma omp barrier
        #pragma omp for schedule(static)
        for (int r = 0; r < nf; r++) {
            double s = 0;
            for (int k = 0; k < nthr; k++) s += tn_tbuf[(size_t)k * nf + r];
            out[r] += 0.5 * s;
        }
    }
}

static double jentry(int r, int c)
{
    MKL_INT lo = ia[r], hi = ia[r + 1] - 1;
    while (lo <= hi) { MKL_INT m = (lo + hi) / 2; if (ja[m] == c) return va[m]; if (ja[m] < c) lo = m + 1; else hi = m - 1; }
    return 0.0;
}

/* 3x3 block-Jacobi of the symmetric part, fixed dofs -> identity rows, shifted until positive definite (drv_px prepare_hess) */
static void bj_setup(void)
{
    #pragma omp parallel for num_threads(nthr)
    for (int64_t i = 0; i < N; i++) {
        double B[3][3];
        for (int p = 0; p < 3; p++) for (int q = 0; q < 3; q++) {
            int rp = fmap[3 * i + p], rq = fmap[3 * i + q];
            B[p][q] = (rp < 0 || rq < 0) ? (p == q ? 1.0 : 0.0) : 0.5 * (jentry(rp, rq) + jentry(rq, rp));
        }
        double tr = B[0][0] + B[1][1] + B[2][2], sh = 0;
        double Bi[3][3] = {{1, 0, 0}, {0, 1, 0}, {0, 0, 1}};
        if (!(tr > 0)) tr = 1.0;
        for (int tries = 0; tries < 30; tries++) {
            double A[3][3];
            for (int p = 0; p < 3; p++) for (int q = 0; q < 3; q++) A[p][q] = B[p][q] + (p == q ? sh : 0);
            int ok = A[0][0] > 0;
            if (ok) {
                double L00 = sqrt(A[0][0]), L10 = A[1][0] / L00, L20 = A[2][0] / L00, l11 = A[1][1] - L10 * L10;
                ok = l11 > 0;
                if (ok) { double L11 = sqrt(l11), L21 = (A[2][1] - L20 * L10) / L11; ok = A[2][2] - L20 * L20 - L21 * L21 > 1e-14 * fabs(tr); }
            }
            if (ok) {
                double det = A[0][0] * (A[1][1] * A[2][2] - A[1][2] * A[2][1]) - A[0][1] * (A[1][0] * A[2][2] - A[1][2] * A[2][0]) +
                             A[0][2] * (A[1][0] * A[2][1] - A[1][1] * A[2][0]);
                Bi[0][0] = (A[1][1] * A[2][2] - A[1][2] * A[2][1]) / det; Bi[0][1] = (A[0][2] * A[2][1] - A[0][1] * A[2][2]) / det;
                Bi[0][2] = (A[0][1] * A[1][2] - A[0][2] * A[1][1]) / det; Bi[1][0] = (A[1][2] * A[2][0] - A[1][0] * A[2][2]) / det;
                Bi[1][1] = (A[0][0] * A[2][2] - A[0][2] * A[2][0]) / det; Bi[1][2] = (A[0][2] * A[1][0] - A[0][0] * A[1][2]) / det;
                Bi[2][0] = (A[1][0] * A[2][1] - A[1][1] * A[2][0]) / det; Bi[2][1] = (A[0][1] * A[2][0] - A[0][0] * A[2][1]) / det;
                Bi[2][2] = (A[0][0] * A[1][1] - A[0][1] * A[1][0]) / det;
                break;
            }
            sh = (sh == 0) ? 1e-3 * fabs(tr) + 1e-8 : 4 * sh;
        }
        for (int p = 0; p < 3; p++) for (int q = 0; q < 3; q++) bjinv[9 * i + 3 * p + q] = Bi[p][q];
    }
}

static void bj_apply(const double *r, double *z)        /* free-dof vectors */
{
    #pragma omp parallel for num_threads(nthr)
    for (int64_t i = 0; i < N; i++)
        for (int p = 0; p < 3; p++) {
            int rp = fmap[3 * i + p];
            if (rp < 0) continue;
            double s = 0;
            for (int q = 0; q < 3; q++) { int rq = fmap[3 * i + q]; if (rq >= 0) s += bjinv[9 * i + 3 * p + q] * r[rq]; }
            z[rp] = s;
        }
}

static double fdot(const double *a, const double *b)
{
    double s = 0;
    #pragma omp parallel for num_threads(nthr) reduction(+:s)
    for (int r = 0; r < nf; r++) s += a[r] * b[r];
    return s;
}

/* Steihaug PCG: H d = -g (H = sym(J)), stop at negative curvature (drv_px pcg) */
static int pcg_energy = 0;               /* 1: the operator is the Hessian of Pi (hessvec_E) */
static int tn_pcg(const double *g, double *d, double eta, int itmax, int *negc)
{
    double *r = malloc(nf * 8), *z = malloc(nf * 8), *p = malloc(nf * 8), *Hp = malloc(nf * 8);
    for (int k = 0; k < nf; k++) { d[k] = 0; r[k] = -g[k]; }
    double rn0 = sqrt(fdot(r, r));
    bj_apply(r, z);
    memcpy(p, z, nf * 8);
    double rz = fdot(r, z);
    int it;
    *negc = 0;
    for (it = 0; it < itmax; it++) {
        if (pcg_energy) hessvec_E(p, Hp); else symv(p, Hp);
        double pHp = fdot(p, Hp);
        if (pHp <= 1e-30 * fdot(p, p)) { *negc = 1; if (it == 0) memcpy(d, z, nf * 8); break; }
        double al = rz / pHp;
        for (int k = 0; k < nf; k++) { d[k] += al * p[k]; r[k] -= al * Hp[k]; }
        if (sqrt(fdot(r, r)) <= eta * rn0) { it++; break; }
        bj_apply(r, z);
        double rz2 = fdot(r, z), be = rz2 / rz;
        rz = rz2;
        for (int k = 0; k < nf; k++) p[k] = z[k] + be * p[k];
    }
    free(r); free(z); free(p); free(Hp);
    n_cg += it;
    return it;
}

/* ------------------------------------------------------------------ separation bookkeeping */
static unsigned char *sepf;            /* per pair id: currently separated */
static int count_pp(void)
{
    int n = 0;
    for (int64_t b = 0; b < nb; b++) n += alive[b] && coh[b] && xb[b] > lb(b);
    return n;
}
static int ca_find(int *p, int a) { while (p[a] != a) { p[a] = p[p[a]]; a = p[a]; } return a; }

/* drv_ghu20: jump-enriched MLS over all candidates (header of mk_drv20.py).  Returns 1 and fills wn on success. */
static int ca_enr = 0;
static long n_enr = 0, n_enr_fb = 0;
static long n_enr_cap = 0, n_enr_cond = 0;
static int ca_enrich(int nc, int *par, int r0, double (*Y)[3], const double *d, double *wn)
{
    /* drv_ghu20b: singleton components (one candidate, not the site's) are dropped and up to 12 further components are
       enriched (basis <= 16). */
    int root[64], cnt[64], nr = 0, ci[64], m = 0, map_[64];
    for (int k = 0; k < nc; k++) {
        int r = ca_find(par, k), e = -1;
        for (int q = 0; q < nr; q++) if (root[q] == r) { e = q; break; }
        if (e < 0) { root[nr] = r; cnt[nr] = 0; e = nr++; }
        cnt[e]++; ci[k] = e;
    }
    for (int q = 0; q < nr; q++) map_[q] = -2;                 /* -2: dropped singleton, -1: the site's component */
    for (int q = 0; q < nr; q++) {
        if (root[q] == r0) map_[q] = -1;
        else if (cnt[q] > 1) { if (m == 12) { n_enr_cap++; return 0; } map_[q] = m++; }
    }
    int nbas = 4 + m;
    double A[256], ev[16], phi[64];
    for (int x = 0; x < nbas * nbas; x++) A[x] = 0.0;
    for (int k = 0; k < nc; k++) {
        int e = map_[ci[k]];
        phi[k] = 0.0;
        if (e == -2) continue;
        double P[16];
        P[0] = 1.0; P[1] = Y[k][0]; P[2] = Y[k][1]; P[3] = Y[k][2];
        for (int x = 4; x < 16; x++) P[x] = 0.0;
        if (e >= 0) P[4 + e] = 1.0;
        phi[k] = exp(-(d[k] / ca_h) * (d[k] / ca_h));
        for (int x = 0; x < nbas; x++) for (int c = 0; c < nbas; c++) A[nbas * x + c] += phi[k] * P[x] * P[c];
    }
    if (LAPACKE_dsyev(LAPACK_ROW_MAJOR, 'V', 'U', nbas, A, nbas, ev) != 0 || !(ev[0] > 0) || ev[nbas - 1] / ev[0] > 1e10) {
        n_enr_cond++;
        return 0;
    }
    double z[16] = {0};
    for (int e_ = 0; e_ < nbas; e_++) for (int x = 0; x < nbas; x++) z[x] += A[nbas * x + e_] * A[e_] / ev[e_];
    for (int k = 0; k < nc; k++) {
        int e = map_[ci[k]];
        if (e == -2) { wn[k] = 0.0; continue; }
        double v = z[0] + Y[k][0] * z[1] + Y[k][1] * z[2] + Y[k][2] * z[3];
        if (e >= 0) v += z[4 + e];
        wn[k] = phi[k] * v;
    }
    return 1;
}

static void ca_init(void)
{
    ngb = 0;
    for (int64_t b = 0; b < nb; b++) ngb += (flag[b] & 1) && sptr[b + 1] - sptr[b] > 1;
    gbl = malloc((ngb ? ngb : 1) * sizeof(int));
    ngb = 0;
    for (int64_t b = 0; b < nb; b++) if ((flag[b] & 1) && sptr[b + 1] - sptr[b] > 1) gbl[ngb++] = (int)b;
    sw0 = malloc(nsup * sizeof(double));
    memcpy(sw0, sw, nsup * sizeof(double));
}

/* crack-aware supports (header drv_ghu19); sepf must be current (count_sep).  Returns the number of ghost bonds whose
   weights changed. */
static int ca_update(void)
{
    int changed = 0;
    if (ca_latch_on && !ca_latch) ca_latch = calloc(nb, 1);
    for (int g = 0; g < ngb; g++) {
        int b = gbl[g];
        if (!alive[b]) continue;
        int64_t q0 = sptr[b];
        int nc = (int)(sptr[b + 1] - q0);
        if (nc > 64) continue;
        int par[64], kn = 0;
        double Y[64][3], d[64], wn[64];
        const double *n = bn + 3 * b; int i = own[b];
        double st[3] = {X[3 * i] - bd0[b] * n[0], X[3 * i + 1] - bd0[b] * n[1], X[3 * i + 2] - bd0[b] * n[2]};
        for (int k = 0; k < nc; k++) {
            int p = sidx[q0 + k];
            par[k] = k;
            for (int c = 0; c < 3; c++) Y[k][c] = X[3 * p + c] - st[c];
            Y[k][2] -= Lz * round(Y[k][2] / Lz);
            d[k] = sqrt(Y[k][0] * Y[k][0] + Y[k][1] * Y[k][1] + Y[k][2] * Y[k][2]);
            if (d[k] < d[kn]) kn = k;
        }
        for (int k = 0; k < nc; k++) {
            int p = sidx[q0 + k];
            for (int o = optr[p]; o < optr[p + 1]; o++) {
                int bb = olist[o];
                if ((flag[bb] & 1) || !alive[bb] || sptr[bb + 1] - sptr[bb] != 1) continue;
                if (ca_thr >= 3.8897) { if (sepf[pairid[bb]]) continue; }
                else if (coh[bb]) {
                    if (ca_latch_on && ca_latch[bb]) continue;
                    if (xb[bb] >= ca_thr * lb(bb)) {
                        if (ca_latch_on) { ca_latch[bb] = 1; n_latched++; }
                        continue;
                    }
                }
                int j = sidx[sptr[bb]];
                for (int k2 = 0; k2 < nc; k2++)
                    if (sidx[q0 + k2] == j) { int ra_ = ca_find(par, k), rb_ = ca_find(par, k2); if (ra_ != rb_) par[ra_] = rb_; break; }
            }
        }
        int r0 = ca_find(par, kn), ncomp = 0;
        for (int k = 0; k < nc; k++) ncomp += ca_find(par, k) == r0;
        if (ncomp == nc) {
            for (int k = 0; k < nc; k++) wn[k] = sw0[q0 + k];
        } else if (ca_enr && ca_enrich(nc, par, r0, Y, d, wn)) {
            n_enr++;
        } else {
            if (ca_enr) n_enr_fb++;
            for (int k = 0; k < nc; k++) wn[k] = 0.0;
            int fb = ncomp < 6;
            if (!fb) {
                double A[16] = {0}, ev[4], phi[64];
                for (int k = 0; k < nc; k++) {
                    if (ca_find(par, k) != r0) continue;
                    double P[4] = {1.0, Y[k][0], Y[k][1], Y[k][2]};
                    phi[k] = exp(-(d[k] / ca_h) * (d[k] / ca_h));
                    for (int a = 0; a < 4; a++) for (int c = 0; c < 4; c++) A[4 * a + c] += phi[k] * P[a] * P[c];
                }
                if (LAPACKE_dsyev(LAPACK_ROW_MAJOR, 'V', 'U', 4, A, 4, ev) != 0 || !(ev[0] > 0) || ev[3] / ev[0] > 1e8) fb = 1;
                else {
                    double z[4] = {0, 0, 0, 0};           /* z = V diag(1/ev) V^T e1, columns of A = eigenvectors */
                    for (int e_ = 0; e_ < 4; e_++) for (int a = 0; a < 4; a++) z[a] += A[4 * a + e_] * A[e_] / ev[e_];
                    for (int k = 0; k < nc; k++)
                        if (ca_find(par, k) == r0) wn[k] = phi[k] * (z[0] + Y[k][0] * z[1] + Y[k][1] * z[2] + Y[k][2] * z[3]);
                }
            }
            if (fb) wn[kn] = 1.0;
        }
        int ch = 0;
        for (int k = 0; k < nc; k++) { if (fabs(wn[k] - sw[q0 + k]) > 1e-14) ch = 1; sw[q0 + k] = wn[k]; }
        changed += ch;
    }
    return changed;
}

static int count_sep(void)
{
    memset(sepf, 0, npid);
    for (int64_t b = 0; b < nb; b++)
        if (alive[b] && coh[b] && xb[b] >= 3.8897 * lb(b)) sepf[pairid[b]] = 1;
    int n = 0;
    for (int p = 0; p < npid; p++) n += sepf[p];
    return n;
}

/* ------------------------------------------------------------------ Newton with line search (as drv_px minimize) */
static double tol = 3.16e-7, lmin = 1.0;
static int maxit = 3000, maxnew = 40;
static long n_relax = 0;
static int verbose = 0;
/* drv_px 'minimize' transcribed to the force-based setting.  Direction d = -J^-1 P_in with the exact tangent first; after
   a failed line search the PD-clipped tangent (axial bond curvature >= clip k0; clip 1e-3, x10 per further failure, max 1;
   back to the exact tangent after a full step).  Line search (cap: max |a d| <= 0.5) on the surrogate energy
   Pi = sum_b phi_b / 2 + T/2 sum D^2 with Armijo slope P_in . d: Pi is the plmode 8 energy for ordinary bonds (exactly
   the fork's minimiser for J04/PX models); for ghost bonds P_in is not its gradient, so a step that halves max |P_in| is
   accepted as well (residual acceptance: local convergence to P_in = 0).  Not a descent direction: Jacobi-scaled -P_in.
   The line-search merit is E* = Pi with the dead-load ghost-force correction at the base point (merit()), so that the
   Armijo slope P_in . d is consistent also for ghost models (for ordinary bonds E* = Pi: the fork's merit).
   When the line search fails or stalls (accepted a < 1e-3; for ghost models the surrogate energy is not the potential of
   P_in, so its line search can stall): 5 pseudo-transient steps (J_clip + mu diag|J|) d = -P_in, capped at l_min / 2,
   always accepted, mu adapted to the residual ratio (implicit overdamped dynamics: consistent with P_in, no energy). */
static int force_finish = 0, cap_relax = 0;
static long n_cap_relaxed = 0, n_jump = 0;
static int solve(double lam, int runaway_ctl, double *err_out, int *runaway);
static int solve_tn(double lam, int runaway_ctl, double *err_out, int *runaway)
{
    for (int64_t k = 0; k < 3 * N; k++) if (fixd[k]) u[k] = lam * ubc[k];
    eval_state();
    double err = gmax_free(), Pi = energy_acc, clp = -1.0;
    int nsep0 = runaway_ctl ? count_sep() : 0, it, nfail = 0, direct = (tn_mode >= 2), nsep_start = count_sep();
    double mu_f = flowmu0, clp_d = -1.0, err_fact = 1.0;
    int reuse_left = 0, reuse_used = 0, etn_its = 0, n_sw_solve = 0, nsep_base_force = 0, force_free = 0;
    (void)nsep_base_force;
    *runaway = 0;
    double *g = malloc(nf * 8), *du = malloc(nf * 8), *u0 = malloc(3 * N * sizeof(double));
    for (it = 0; it < maxit && err > tol; it++) {
        double ta = omp_get_wtime();
        int negc = 0, was_direct = direct, npp_base = direct ? count_pp() : 0, nsep_base = direct ? count_sep() : 0;
        if (direct) {                                    /* hybrid: exact Newton direction (PARDISO, nonsymmetric) */
            clip_on = ((tn_mode == 5 || tn_mode == 6) && clp_d > 0); clipf = clp_d;
            long drop = assemble();
            if (drop) { printf("ERROR off-pattern entries %ld\n", drop); exit(5); }
            for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0) { g[fmap[k]] = fint[k]; rhs[fmap[k]] = -fint[k]; }
            t_asm += omp_get_wtime() - ta;
            int perr = psolve(du);
            n_newton++;
            if (perr || (!(fdot(g, du) < 0) && !force_free)) { direct = 0; n_switch++; it--; continue; }
        } else if (tn_mode == 4 || tn_mode == 5) {        /* overdamped flow (PTC) step, always accepted */
            int perr;
            if (reuse_left <= 0) {                        /* new factorisation of J_clip + mu diag|J| */
                if (reuse_used > 0) {                     /* SER on the cumulative residual ratio since the last one */
                    double qc = err / err_fact;
                    mu_f *= (qc < 0.1 ? 0.1 : (qc > 5 ? 5 : qc));
                    if (mu_f < 1e-6) mu_f = 1e-6;
                }
                clip_on = 1; clipf = 1e-3;
                long drop = assemble();
                if (drop) { printf("ERROR off-pattern entries %ld\n", drop); exit(5); }
                for (int r = 0; r < nf; r++) va[dpos[r]] += mu_f * (dabs_[r] > 0 ? dabs_[r] : 1.0);
                for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0) rhs[fmap[k]] = -fint[k];
                t_asm += omp_get_wtime() - ta;
                perr = psolve(du);
                reuse_left = flowreuse; reuse_used = 0; err_fact = err;
            } else {
                for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0) rhs[fmap[k]] = -fint[k];
                perr = psolve_reuse(du);
            }
            reuse_left--; reuse_used++;
            n_newton++; n_flow++;
            if (perr) { mu_f *= 10; reuse_left = 0; continue; }
            double dmf = 0;
            for (int r = 0; r < nf; r++) if (fabs(du[r]) > dmf) dmf = fabs(du[r]);
            double af = (dmf > flowcap * lmin) ? flowcap * lmin / dmf : 1.0;
            memcpy(u0, u, 3 * N * sizeof(double));
            for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0) u[k] = u0[k] + af * du[fmap[k]];
            eval_state();
            double enf = gmax_free();
            if (!isfinite(enf)) { memcpy(u, u0, 3 * N * sizeof(double)); eval_state(); mu_f *= 10; reuse_left = 0; reuse_used = 0; n_reject++; continue; }
            double q = enf / err;
            if (q > 0.9) reuse_left = 0;                  /* stalled with the stale factor: refactorise */
            err = enf; Pi = energy_acc;
            if (verbose) printf("  flow %d err %.3e a %.3g dm %.3g mu %.2e nsep %d npp %d\n", it, err, af, dmf, mu_f, count_sep(), count_pp());
            if (runaway_ctl && count_sep() - nsep0 > maxnew) { *runaway = 1; it++; break; }
            if (err < 1e-3) { direct = 1; clp_d = -1.0; reuse_left = 0; reuse_used = 0; }  /* near equilibrium again: Newton */
            continue;
        } else if (tn_mode == 6) {                        /* separation event: fork truncated Newton on Pi */
            clip_on = clp > 0; clipf = clp; hclip_on = clp > 0; hclipf = clp;
            long drop = assemble();
            if (drop) { printf("ERROR off-pattern entries %ld\n", drop); exit(5); }
            bj_setup();
            double errE = 0;
            for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0) { g[fmap[k]] = gE[k]; if (fabs(gE[k]) > errE) errE = fabs(gE[k]); }
            t_asm += omp_get_wtime() - ta;
            double eta = fmin(0.1, sqrt(errE)); if (eta < 1e-3) eta = 1e-3;
            double tc = omp_get_wtime();
            pcg_energy = 1;
            tn_pcg(g, du, eta, 2000, &negc);
            pcg_energy = 0;
            t_fact += omp_get_wtime() - tc;
            n_newton++; n_etn++;
            double slopeE = fdot(g, du);
            if (!(slopeE < 0)) { bj_apply(g, du); for (int r = 0; r < nf; r++) du[r] = -du[r]; slopeE = fdot(g, du); }
            double dmE = 0;
            for (int r = 0; r < nf; r++) if (fabs(du[r]) > dmE) dmE = fabs(du[r]);
            double PiE = energy_acc, aE = (dmE > 0.5) ? 0.5 / dmE : 1.0, PnE = PiE;
            memcpy(u0, u, 3 * N * sizeof(double));
            int okE = 0;
            for (int ls = 0; ls < 40; ls++) {
                for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0) u[k] = u0[k] + aE * du[fmap[k]];
                eval_state();
                PnE = energy_acc;
                double eE = 0;
                for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0 && fabs(gE[k]) > eE) eE = fabs(gE[k]);
                if (isfinite(PnE) && PnE <= PiE + 1e-4 * aE * slopeE) { okE = 1; break; }
                if (isfinite(PnE) && fabs(PnE - PiE) <= 1e-12 * fabs(PiE) && eE < errE) { okE = 1; break; }
                aE *= 0.5;
            }
            if (!okE) {
                memcpy(u, u0, 3 * N * sizeof(double));
                eval_state();
                n_reject++;
                clp = (clp < 0) ? 1e-3 : fmin(1.0, clp * 10);
                if (++nfail > 6) {                         /* hand over to the force solver */
                    if (nsup > nb) {
                        int r2 = 0;
                        force_finish = 1;
                        it += solve(lam, runaway_ctl, &err, &r2);
                        force_finish = 0;
                        if (r2) *runaway = 1;
                        n_force_finish++;
                        break;
                    }
                    direct = 1; clp_d = -1.0; nfail = 0; force_free = 1;
                }
                continue;
            }
            if (aE == 1.0) clp = -1.0;
            err = gmax_free(); Pi = energy_acc;
            double eEn = 0;
            for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0 && fabs(gE[k]) > eEn) eEn = fabs(gE[k]);
            if (verbose) printf("  etn %d |dPi| %.3e |P_in| %.3e a %.3g dm %.3g clip %.0e negc %d nsep %d\n", it, eEn, err, aE, dmE, clp, negc, count_sep());
            if (runaway_ctl && count_sep() - nsep0 > (nsup == nb ? maxnew : 4 * maxnew)) {
                if (cap_relax && nsup > nb) {             /* drv_ghu16: decide on the force equilibrium (see header) */
                    int r2 = 0;
                    force_finish = 1;
                    it += solve(lam, 0, &err, &r2);
                    force_finish = 0;
                    n_force_finish++; n_cap_relaxed++;
                    if (count_sep() - nsep0 > maxnew) *runaway = 1;
                    break;
                }
                *runaway = 1; it++; break;
            }
            if (eEn < tol || (++etn_its > 400 && eEn < 1e-4)) {
                if (nsup > nb) {                          /* ghost model: force equilibrium by the drv_ghu solver from here */
                    int r2 = 0;
                    force_finish = 1;
                    it += solve(lam, runaway_ctl, &err, &r2);
                    force_finish = 0;
                    if (r2) *runaway = 1;
                    n_force_finish++;
                    break;
                }
                direct = 1; clp_d = -1.0; etn_its = 0; nsep_base_force = count_sep(); force_free = 1;
            }
            continue;
        } else {
        clip_on = clp > 0; clipf = clp;
        long drop = assemble();
        if (drop) { printf("ERROR off-pattern entries %ld\n", drop); exit(5); }
        bj_setup();
        for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0) g[fmap[k]] = fint[k];
        t_asm += omp_get_wtime() - ta;
        double eta = fmin(0.1, sqrt(err)); if (eta < 1e-3) eta = 1e-3;
        double tc = omp_get_wtime();
        tn_pcg(g, du, eta, 2000, &negc);
        t_fact += omp_get_wtime() - tc;
        n_newton++;
        if (clip_on) n_relax++;
        if (tn_mode == 3 && !negc && !clip_on) {          /* convex here: exact Newton trial, PCG step kept as fallback */
            double *dn = malloc(nf * 8);
            for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0) rhs[fmap[k]] = -fint[k];
            int perr = psolve(dn);
            if (!perr && fdot(g, dn) < 0) {
                double dmn = 0;
                for (int r = 0; r < nf; r++) if (fabs(dn[r]) > dmn) dmn = fabs(dn[r]);
                if (dmn <= 0.5) {
                    int nppb = count_pp(), nsb = count_sep();
                    memcpy(u0, u, 3 * N * sizeof(double));
                    for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0) u[k] = u0[k] + dn[fmap[k]];
                    eval_state();
                    double ent = gmax_free();
                    if (isfinite(ent) && ent <= 0.5 * err && count_pp() <= nppb && count_sep() <= nsb) {
                        n_exact_in_tn++;
                        err = ent; Pi = energy_acc; clp = -1.0;
                        free(dn);
                        if (verbose) printf("  tn-exact %d err %.3e\n", it, err);
                        if (runaway_ctl && count_sep() - nsep0 > maxnew) { *runaway = 1; it++; break; }
                        continue;
                    }
                    memcpy(u, u0, 3 * N * sizeof(double));
                    eval_state();
                }
            }
            free(dn);
        }
        }
        double slope = fdot(g, du);
        if (!(slope < 0) && was_direct && force_free) slope = -1e-300;   /* force phase: keep the Newton direction, accept on the residual */
        else if (!(slope < 0)) { bj_apply(g, du); for (int r = 0; r < nf; r++) du[r] = -du[r]; slope = fdot(g, du); }
        double dm = 0;
        for (int r = 0; r < nf; r++) if (fabs(du[r]) > dm) dm = fabs(du[r]);
        merit_base();
        Pi = energy_acc;
        double a = (dm > 0.5) ? 0.5 / dm : 1.0, en = err, Pn = Pi;
        memcpy(u0, u, 3 * N * sizeof(double));
        int ok = 0;
        for (int ls = 0; ls < 40; ls++) {
            for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0) u[k] = u0[k] + a * du[fmap[k]];
            eval_state();
            Pn = merit(); en = gmax_free();
            if (isfinite(en) && Pn <= Pi + 1e-4 * a * slope) { ok = 1; break; }
            if (isfinite(en) && fabs(Pn - Pi) <= 1e-12 * fabs(Pi) && en < err) { ok = 1; break; }
            if (isfinite(en) && nsup > nb && en < 0.5 * err) { ok = 1; break; }      /* ghost models: residual acceptance */
            a *= 0.5;
        }
        if (was_direct && (tn_mode == 5 || tn_mode == 6)) {
            if ((!ok || count_sep() > nsep_base) && (tn_mode == 5 || (n_sw_solve < 30 && !force_free))) {
                memcpy(u, u0, 3 * N * sizeof(double));
                eval_state();
                direct = 0; n_switch++; n_sw_solve++; mu_f = flowmu0; reuse_left = 0; reuse_used = 0; clp = -1.0; nfail = 0;
                continue;
            }
            if (!ok) {                                    /* ping-pong guard reached: plain failure handling */
                memcpy(u, u0, 3 * N * sizeof(double));
                eval_state();
                n_reject++;
                clp_d = (clp_d < 0) ? 1e-3 : fmin(1.0, clp_d * 10);
                if (++nfail > 6) break;
                continue;
            }
            if (clp_d < 0 && en > 0.5 * err) clp_d = 1e-3;        /* slow exact step: PD-clipped tangent next */
            else if (clp_d > 0 && a >= 1.0) clp_d = -1.0;        /* full clipped step: exact again */
            Pi = Pn; err = en;
            if (verbose) printf("  nt %d err %.3e a %.3g dm %.3g clip %.0e npp %d\n", it, err, a, dm, clp_d, count_pp());
            if (runaway_ctl && (tn_mode != 6 || nsup == nb) && count_sep() - nsep0 > maxnew) { *runaway = 1; it++; break; }
            continue;
        }
        if (was_direct && (!ok || a < 1.0 || en > 0.5 * err || count_sep() > (tn_mode == 4 ? nsep_base : nsep_start) || (pprule && count_pp() > npp_base))) {
            memcpy(u, u0, 3 * N * sizeof(double));                   /* hybrid: the exact step was only a trial */
            eval_state();
            direct = 0; n_switch++;
            continue;
        }
        if (!ok) {
            memcpy(u, u0, 3 * N * sizeof(double));
            eval_state();
            n_reject++;
            clp = (clp < 0) ? 1e-3 : fmin(1.0, clp * 10);
            if (++nfail > 6) break;
            continue;
        }
        if (a == 1.0) clp = -1.0;
        Pi = Pn; err = en;
        if (verbose) printf("  tn %d err %.3e Pi %.10e a %.3g dm %.3g clip %.0e negc %d nsep %d\n", it, err, Pi, a, dm, clp, negc, count_sep());
        if (runaway_ctl && count_sep() - nsep0 > maxnew) { *runaway = 1; it++; break; }
    }
    clip_on = 0;
    /* ghost models (energy-guided mode): the runaway check on the converged force equilibrium only */
    if (tn_mode == 6 && nsup > nb && runaway_ctl && count_sep() - nsep0 > maxnew) *runaway = 1;
    free(g); free(du); free(u0);
    *err_out = err;
    return it;
}

static int solve(double lam, int runaway_ctl, double *err_out, int *runaway)
{
    if (tn_mode && !force_finish) return solve_tn(lam, runaway_ctl, err_out, runaway);
    for (int64_t k = 0; k < 3 * N; k++) if (fixd[k]) u[k] = lam * ubc[k];
    eval_state();
    double err = gmax_free(), Pi = energy_acc, clp = -1.0, mu = 1.0;   /* clp < 0: exact tangent */
    int nsep0 = runaway_ctl ? count_sep() : 0, it, pt_left = 0;
    *runaway = 0;
    double *du = malloc(nf * sizeof(double)), *u0 = malloc(3 * N * sizeof(double));
    for (it = 0; it < maxit && err > tol; it++) {
        double ta = omp_get_wtime();
        if (pt_left > 0) {                               /* pseudo-transient step */
            clip_on = 1; clipf = 1e-3;
            long drop = assemble();
            if (drop) { printf("ERROR off-pattern entries %ld\n", drop); exit(5); }
            for (int r = 0; r < nf; r++) va[dpos[r]] += mu * (dabs_[r] > 0 ? dabs_[r] : 1.0);
            for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0) rhs[fmap[k]] = -fint[k];
            t_asm += omp_get_wtime() - ta;
            int perr = psolve(du);
            n_newton++; n_relax++; pt_left--;
            if (perr) { mu *= 10; continue; }
            double dm = 0;
            for (int r = 0; r < nf; r++) if (fabs(du[r]) > dm) dm = fabs(du[r]);
            double a = (dm > 0.5 * lmin) ? 0.5 * lmin / dm : 1.0;
            memcpy(u0, u, 3 * N * sizeof(double));
            for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0) u[k] = u0[k] + a * du[fmap[k]];
            eval_state();
            double en = gmax_free();
            if (!isfinite(en)) { memcpy(u, u0, 3 * N * sizeof(double)); eval_state(); mu *= 10; n_reject++; continue; }
            double q = en / err;
            mu *= (q < 0.2 ? 0.2 : (q > 5 ? 5 : q));
            if (mu < 1e-4) mu = 1e-4;
            err = en; Pi = energy_acc;
            if (verbose) {
                int64_t km = 0; double fm = 0;
                for (int64_t k = 0; k < 3 * N; k++) if (!fixd[k] && fabs(fint[k]) > fm) fm = fabs(fint[k]), km = k;
                int ip = (int)(km / 3), nal = 0, ngh = 0, nsepb = 0, nsupof = 0;
                for (int k = optr[ip]; k < optr[ip + 1]; k++) {
                    int b = olist[k];
                    if (!alive[b]) continue;
                    nal++; ngh += flag[b] & 1; nsepb += coh[b] && xb[b] >= 3.8897 * lb(b);
                }
                if (verbose > 1) for (int64_t q = 0; q < nsup; q++) nsupof += sidx[q] == ip;
                printf("  pt %d err %.3e Pi %.10e a %.3g dm %.3g mu %.2e nsep %d t_fact %.0f | max at particle %d (%.2f, %.2f) dof %d: "
                       "bonds %d (ghost %d, separated %d), support of %d\n", it, err, Pi, a, dm, mu, count_sep(), t_fact, ip, X[3 * ip],
                       X[3 * ip + 1], (int)(km % 3), nal, ngh, nsepb, nsupof);
            }
            if (runaway_ctl && count_sep() - nsep0 > maxnew) { *runaway = 1; it++; break; }
            continue;
        }
        clip_on = clp > 0;
        clipf = clp;
        long drop = assemble();
        if (drop) { printf("ERROR off-pattern entries %ld\n", drop); exit(5); }
        for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0) rhs[fmap[k]] = -fint[k];
        t_asm += omp_get_wtime() - ta;
        int perr = psolve(du);
        n_newton++;
        if (clip_on) n_relax++;
        double slope = 0;
        for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0) slope += fint[k] * du[fmap[k]];
        if (perr || !(slope < 0)) {                      /* not a descent direction: Jacobi-scaled force */
            slope = 0;
            for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0) {
                int r = fmap[k];
                du[r] = -fint[k] / (dabs_[r] > 0 ? dabs_[r] : 1.0);
                slope += fint[k] * du[r];
            }
        }
        double dm = 0;
        for (int r = 0; r < nf; r++) if (fabs(du[r]) > dm) dm = fabs(du[r]);
        merit_base();                                    /* E* at u0 = Pi(u0) */
        Pi = energy_acc;
        double a = (dm > 0.5) ? 0.5 / dm : 1.0, en = err, Pn = Pi;
        memcpy(u0, u, 3 * N * sizeof(double));
        int ok = 0;
        for (int ls = 0; ls < 40; ls++) {
            for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0) u[k] = u0[k] + a * du[fmap[k]];
            eval_state();
            Pn = merit(); en = gmax_free();
            if (isfinite(en) && Pn <= Pi + 1e-4 * a * slope) { ok = 1; break; }
            if (isfinite(en) && en < 0.5 * err) { ok = 1; break; }
            a *= 0.5;
            if (a < 1e-3) break;
        }
        if (ok && a == 1.0 && en > 0.5 * err && dm < 0.5) {
            /* expanding line search along a slowly converging direction (negative-curvature region, e.g. a running crack;
               drv_px's Steihaug-CG moves along such a direction up to the 0.5 cap): double the step while the energy keeps
               decreasing (Armijo), up to max |a d| = 0.5 */
            double abest = 1.0, Pbest = Pn;
            for (double at = 2.0; at * dm <= 0.5 + 1e-12; at *= 2.0) {
                for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0) u[k] = u0[k] + at * du[fmap[k]];
                eval_state();
                double Pt = merit();
                if (!isfinite(gmax_free()) || !(Pt < Pbest) || Pt > Pi + 1e-4 * at * slope) break;
                abest = at; Pbest = Pt;
            }
            for (int64_t k = 0; k < 3 * N; k++) if (fmap[k] >= 0) u[k] = u0[k] + abest * du[fmap[k]];
            eval_state();
            Pn = merit(); en = gmax_free(); a = abest;
        }
        if (!ok) {                                       /* line search failed or stalled: pseudo-transient steps */
            memcpy(u, u0, 3 * N * sizeof(double));
            eval_state();
            n_reject++;
            clp = (clp < 0) ? 1e-3 : fmin(1.0, clp * 10);
            pt_left = 5;
            continue;
        }
        /* exact tangent only while it converges (residual at least halved); a slow exact step means negative curvature
           (the direct solve heads for the saddle, where Steihaug-CG in drv_px would follow the negative curvature):
           switch to the PD-clipped tangent; back to exact after a full clipped step (as drv_px) */
        if (clp < 0 && en > 0.5 * err) clp = 1e-3;
        else if (clp > 0 && a >= 1.0) clp = -1.0;
        Pi = Pn; err = en;
        if (verbose) printf("  it %d err %.3e Pi %.10e a %.3g dm %.3g clip %.0e slope %.3e nsep %d t_fact %.0f\n", it, err, Pi, a, dm, clp,
                            slope, count_sep(), t_fact);
        if (runaway_ctl && count_sep() - nsep0 > maxnew) { *runaway = 1; it++; break; }
    }
    clip_on = 0;
    free(du); free(u0);
    *err_out = err;
    return it;
}

