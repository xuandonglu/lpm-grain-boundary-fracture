static int64_t N, nb, nsup;
static int ver;
static double T, s_c, tie, kg, Lz, ul[2] = {1, 1}, y0c, Hd, Wd, a0c;
static int emode = 0;                     /* drv_ghu18: P_in := dPi/du */
static int ca_on = 0, ngb = 0, *gbl = NULL;  /* drv_ghu20 (generated by mk_drv20.py from drv_ghu19.c; adds GH_CAENR) -- drv_ghu19: crack-aware ghost supports */
static double *sw0 = NULL, ca_h = 0.9, ca_thr = 3.8897;
static int ca_latch_on = 0;                    /* drv_ghu21: GH_CALATCH -- monotone (latched) split criterion */
static unsigned char *ca_latch = NULL;
static long n_latched = 0;
static long n_ca_updates = 0, n_ca_changed = 0;
